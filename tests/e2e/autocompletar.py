import os, shutil
PROFILES = os.environ.get("POIESIS_PROFILES", "/tmp/poiesis-e2e")
SHOTS = os.environ.get("POIESIS_SHOTS", "/tmp/poiesis-e2e/capturas")
os.makedirs(SHOTS, exist_ok=True)
import time, pathlib
from playwright.sync_api import sync_playwright
EXT = os.path.abspath(os.environ.get("POIESIS_DIST", os.path.join(os.path.dirname(__file__), "..", "..", "dist")))
errs=[]; results={}
def check(name, cond, extra=""):
    results[name]=bool(cond); print(("OK  " if cond else "FALHOU ")+name, extra)
def opts(page): return [o.replace("\n"," ") for o in page.locator(".cm-tooltip-autocomplete li").all_inner_texts()]
def doc(page): return page.evaluate("() => document.querySelector('.cm-content').cmView ? '' : ''") or page.locator(".cm-content").first.inner_text()
with sync_playwright() as p:
    shutil.rmtree(os.path.join(PROFILES, "pv4"), ignore_errors=True)
    ctx = p.chromium.launch_persistent_context(os.path.join(PROFILES, "pv4"), channel="chromium", headless=True, args=[f"--disable-extensions-except={EXT}", f"--load-extension={EXT}"], viewport={"width":1440,"height":900})
    sw = ctx.service_workers[0] if ctx.service_workers else ctx.wait_for_event("serviceworker", timeout=15000)
    ext = sw.url.split("/")[2]; time.sleep(1.5)
    pages=[pg for pg in ctx.pages if ext in pg.url]
    page = pages[0] if pages else ctx.new_page()
    if not pages: page.goto(f"chrome-extension://{ext}/index.html")
    page.on("console", lambda m: errs.append(f"[{m.type}] {m.text}") if m.type=="error" else None)
    page.on("pageerror", lambda e: errs.append(f"[pageerror] {e}"))
    page.wait_for_timeout(2500)
    inner = page.frame_locator("iframe[title=Preview]").frame_locator("iframe")
    # adicionar imagens ao projeto (pasta img)
    page.locator("input[type=file][webkitdirectory]").set_input_files(str((pathlib.Path(__file__).parent / "fixtures" / "site2").resolve()))
    page.wait_for_timeout(800)
    if page.get_by_role("button", name="Adicionar", exact=True).count(): page.get_by_role("button", name="Adicionar", exact=True).click()
    page.wait_for_timeout(1200)
    tree = page.locator("[data-explorer]").inner_text()
    check("imagens adicionadas", "foto.png" in tree and "logo.svg" in tree, tree.replace("\n"," | ")[:160])
    page.locator("div[title='index.html']").click(); page.wait_for_timeout(400)
    ed = page.locator(".cm-content").first
    ed.click(); page.keyboard.press("Control+Home")
    # vai para a linha antes de </body>
    for _ in range(20): page.keyboard.press("ArrowDown")
    page.keyboard.press("End")
    page.keyboard.type("\n<im"); page.wait_for_timeout(900)
    o = opts(page); check("<img sugere imagens do projeto", any("img →" in x and "foto.png" in x for x in o), o[:6])
    page.screenshot(path=os.path.join(SHOTS, "v4-1-img.png"))
    sel = [i for i,x in enumerate(o) if "foto.png" in x][0] if any("foto.png" in x for x in o) else 0
    for _ in range(sel): page.keyboard.press("ArrowDown")
    page.keyboard.press("Enter"); page.wait_for_timeout(300)
    page.keyboard.press("Escape")
    check("<img> inserido com src", 'img src="img/foto.png"' in ed.inner_text(), "")
    page.keyboard.press("End"); page.keyboard.type("\n<li"); page.wait_for_timeout(800)
    o = opts(page); check("<link sugere css e favicon", any("link →" in x and "style.css" in x for x in o) and any("link →" in x and "logo.svg" in x for x in o), o[:6])
    page.keyboard.press("Escape"); page.keyboard.press("Control+z")
    page.keyboard.press("End"); page.keyboard.type('\n<script src="'); page.wait_for_timeout(900)
    o = opts(page); check("src=\" abre sozinho com .js", any("script.js" in x for x in o), o[:5])
    page.keyboard.press("Escape")
    page.keyboard.press("End"); page.keyboard.type('></script>\n<div data-tema="claro" style="back'); page.wait_for_timeout(900)
    o = opts(page); check("style=\"\" sugere propriedades", any(x.startswith("background") for x in o), o[:4])
    page.keyboard.press("Escape"); page.keyboard.type("ground-color: tra"); page.wait_for_timeout(900)
    o = opts(page); check("style=\"\" sugere valores", o and o[0].startswith("transparent"), o[:6])
    page.keyboard.press("Escape"); page.keyboard.type('nsparent">\n<span class="material-symbols-rounded">sett'); page.wait_for_timeout(1500)
    o = opts(page); check("nomes de ícones no <span>", o and o[0].startswith("settings"), o[:4])
    page.screenshot(path=os.path.join(SHOTS, "v4-2-iconac.png"))
    page.keyboard.press("Enter"); page.keyboard.press("End"); page.keyboard.type("</span></div>")
    # seletor de ícones
    page.keyboard.press("End"); page.keyboard.type("\n"); page.keyboard.press("Alt+i"); page.wait_for_timeout(1200)
    check("seletor abre", page.get_by_text("Material Symbols", exact=True).count() > 0)
    page.keyboard.type("casa"); page.wait_for_timeout(500)
    first = page.locator("[data-name]").first.get_attribute("data-name")
    check("busca em português (casa → home)", first in ("home", "house", "cottage"), first)
    page.screenshot(path=os.path.join(SHOTS, "v4-3-picker.png"))
    page.keyboard.press("Enter"); page.wait_for_timeout(1500)
    t = ed.inner_text()
    check("span inserido", '<span class="material-symbols-rounded">'+first+'</span>' in t)
    check("link da fonte adicionado no head", "family=Material+Symbols+Rounded" in t.split("</head>")[0])
    check("ícone no preview", inner.locator(f"span.material-symbols-rounded:text('{first}')").count() >= 1)
    # trocar ícone pelo menu de contexto
    # cursor está logo após </span> inserido: volta 9 caracteres (para dentro do nome)
    for _ in range(9): page.keyboard.press("ArrowLeft")
    box = page.locator(".cm-cursor-primary").bounding_box()
    page.mouse.click(box["x"]+1, box["y"]+box["height"]/2, button="right"); page.wait_for_timeout(400)
    item = page.locator("[role=menuitem]", has_text="Trocar ícone")
    check("menu mostra 'Trocar ícone'", item.count() > 0)
    if item.count():
        item.click(); page.wait_for_timeout(800)
        page.keyboard.press("Control+a"); page.keyboard.type("estrela"); page.wait_for_timeout(500)
        nm = page.locator("[data-name]").first.get_attribute("data-name")
        page.keyboard.press("Enter"); page.wait_for_timeout(600)
        check("ícone trocado", '>'+nm+'</span>' in ed.inner_text() and '>'+first+'</span>' not in ed.inner_text(), nm)
    # CSS: font-family
    page.locator("div[title='style.css']").click(); page.wait_for_timeout(300)
    ed.click(); page.keyboard.press("Control+End"); page.keyboard.type("\n.ic { font-family: "); page.wait_for_timeout(900)
    o = opts(page); check("font-family sugere Material Symbols", any("Material Symbols" in x for x in o), o[:4])
    page.keyboard.press("Escape"); page.keyboard.type("x; background: url("); page.wait_for_timeout(900)
    o = opts(page); check("url( sugere imagens", any("img/foto.png" in x for x in o), o[:4])
    page.keyboard.press("Escape"); page.keyboard.type("img/foto.png); }\n[data"); page.wait_for_timeout(900)
    o = opts(page); check("[data sugere data-* do HTML", any("data-tema" in x for x in o), o[:4])
    page.keyboard.press("Escape")
    # JS
    page.locator("div[title='script.js']").click(); page.wait_for_timeout(300)
    ed.click(); page.keyboard.press("Control+End")
    page.keyboard.type('\nlocalStorage.setItem("tema", "claro");\nconst x = document.createElement("'); page.wait_for_timeout(900)
    o = opts(page); check("createElement sugere tags", any(x.startswith("div") for x in o), o[:4])
    page.keyboard.press("Escape"); page.keyboard.type('div");\nx.dataset.'); page.wait_for_timeout(900)
    o = opts(page); check("dataset. sugere data-*", any(x.startswith("tema") for x in o), o[:4])
    page.keyboard.press("Escape"); page.keyboard.type('tema;\nlocalStorage.getItem("'); page.wait_for_timeout(1200)
    o = opts(page); check("getItem sugere chaves salvas", any(x.startswith("tema") for x in o), o[:4])
    page.keyboard.press("Escape"); page.keyboard.type('tema");\nx.style.bac'); page.wait_for_timeout(900)
    o = opts(page); check("style. sugere props em camelCase", any(x.startswith("backgroundColor") for x in o), o[:4])
    page.keyboard.press("Escape"); page.keyboard.type('kground = "red";\nconst im = new Image(); im.src = "'); page.wait_for_timeout(900)
    o = opts(page); check(".src = sugere arquivos", any("img/foto.png" in x for x in o), o[:4])
    page.keyboard.press("Escape")
    page.screenshot(path=os.path.join(SHOTS, "v4-4-js.png"))
    # localStorage no preview (sandbox) + persistência entre execuções
    page.wait_for_timeout(1500)
    ta = page.locator("textarea[placeholder^='Avaliar']")
    ta.fill("localStorage.getItem('tema') + '|' + localStorage.length"); ta.press("Enter"); page.wait_for_timeout(800)
    con = page.locator("textarea[placeholder^='Avaliar']").locator("xpath=../..").inner_text()
    check("localStorage funciona no preview", "claro|1" in con, con[-120:].replace("\n"," | "))
    page.keyboard.press("Control+Enter"); page.wait_for_timeout(1500)
    ta.fill("localStorage.getItem('tema')"); ta.press("Enter"); page.wait_for_timeout(800)
    con = page.locator("textarea[placeholder^='Avaliar']").locator("xpath=../..").inner_text()
    check("localStorage persiste ao executar de novo", '"claro"' in con or "claro" in con.split("localStorage.getItem('tema')")[-1], con[-80:].replace("\n"," | "))
    print("ERROS DA PÁGINA:", [e for e in errs if "dataset" not in e and "TUNNEL" not in e][:8])
    print("RESUMO:", sum(results.values()), "/", len(results))
    ctx.close()
