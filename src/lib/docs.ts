/* ---------- fallback do MDN (carregado sob demanda) ---------- */
type Mdn = {
  css: Record<string, [string, string, string[]]>;
  at: Record<string, string>;
  pseudo: Record<string, string>;
  tags: Record<string, [string, Record<string, string>]>;
  attrs: Record<string, string>;
};
let mdnPromise: Promise<Mdn> | null = null;
export function loadMdn(): Promise<Mdn> {
  if (!mdnPromise) mdnPromise = import("./mdn-data.json").then((m) => (m.default ?? m) as unknown as Mdn);
  return mdnPromise;
}
let mdnSync: Mdn | null = null;
loadMdnLater();
function loadMdnLater() {
  setTimeout(() => loadMdn().then((m) => (mdnSync = m)), 3000);
}
export const mdnNow = () => mdnSync;
